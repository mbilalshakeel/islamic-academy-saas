def esc(s):
    """SQL string literal escaping. None -> NULL."""
    if s is None:
        return "NULL"
    return "'" + str(s).replace("'", "''") + "'"

def esc_arr(arr):
    if not arr:
        return "'{}'"
    escaped = [str(x).replace("'", "''").replace(",", "\\,") for x in arr]
    inner = ",".join(escaped)
    return "'{" + inner + "}'"

