def parse_rakat_breakdown(rakat_text):
    """'4 Sunnah, 4 Fard, 2 Sunnah, 2 Nafl' -> ordered JSON list + summary totals."""
    parts = [p.strip() for p in rakat_text.split(",")]
    breakdown = []
    totals = {"Fard": 0, "Sunnah": 0, "Nafl": 0, "Witr": 0}
    for p in parts:
        count_str, type_str = p.split(" ", 1)
        count = int(count_str)
        breakdown.append({"type": type_str, "count": count})
        if type_str in totals:
            totals[type_str] += count
    return breakdown, totals

